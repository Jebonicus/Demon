#!/usr/bin/env bash
# Makes the ReSpeaker XVF3800 the default sound device, with:
#   - capture taken from the XVF3800's ASR channel (channel 1: echo-cancelled,
#     noise-suppressed, tuned for speech recognition)
#   - a software volume control with a hard ceiling, so nothing can turn the
#     demon up loud enough to annoy the neighbours
#
# Usage: bash audio-setup.sh [max_dB]      (default ceiling: -6 dB)
# Then set the everyday level with:  amixer -c <card> sset 'Demon' 80%
set -euo pipefail
MAX_DB="${1:--6.0}"

CARD="$(awk -F'[][]' '/[Xx][Vv][Ff]|[Rr]e[Ss]peaker|[Aa]rray/ {gsub(/ /,"",$2); print $2; exit}' /proc/asound/cards)"
if [ -z "$CARD" ]; then
  echo "Couldn't find the XVF3800 in /proc/asound/cards:"; cat /proc/asound/cards; exit 1
fi
echo "Using ALSA card: $CARD"
arecord -D "hw:$CARD" --dump-hw-params -d 1 /dev/null 2>&1 | grep -E 'CHANNELS|RATE' || true

sudo tee /etc/asound.conf >/dev/null <<EOF
# Generated by demon-robot/pi/audio-setup.sh
pcm.!default {
    type asym
    playback.pcm "demon_out"
    capture.pcm  "demon_in"
}
ctl.!default { type hw card "$CARD" }

# Playback: plug (rate/format conversion) -> softvol (capped) -> XVF3800.
# Going out through the XVF3800 is what gives its echo canceller the reference signal.
pcm.demon_out {
    type plug
    slave.pcm "demon_softvol"
}
pcm.demon_softvol {
    type softvol
    slave.pcm "plughw:$CARD,0"
    control { name "Demon"; card "$CARD" }
    min_dB -40.0
    max_dB $MAX_DB
}

# Capture: XVF3800 USB firmware sends 2 channels: 0 = conference, 1 = ASR.
# Take channel 1 only, as mono.
pcm.demon_in {
    type plug
    slave.pcm "demon_asr"
}
pcm.demon_asr {
    type route
    slave { pcm "hw:$CARD,0"; channels 2 }
    ttable.0.1 1
}
EOF

# The softvol control only appears after the first playback through it.
speaker-test -D default -c 1 -t sine -f 440 -l 1 >/dev/null 2>&1 &
sleep 2; kill $! 2>/dev/null || true
amixer -c "$CARD" sset 'Demon' 80% >/dev/null 2>&1 || true
# Put the board's own hardware volume at full; softvol does the limiting.
for ctl in PCM Speaker Playback; do amixer -c "$CARD" sset "$ctl" 100% >/dev/null 2>&1 || true; done

echo
echo "Audio configured. Test it:"
echo "  speaker-test -D default -c 1 -t wav -l 1      # should talk through the speaker"
echo "  arecord -D default -f S16_LE -r 16000 -c 1 -d 5 /tmp/t.wav && aplay /tmp/t.wav"
echo "  alsamixer -c $CARD                             # 'Demon' = everyday volume (ceiling ${MAX_DB} dB)"
echo "If recording is silent, try ttable.0.0 instead of ttable.0.1 in /etc/asound.conf."
